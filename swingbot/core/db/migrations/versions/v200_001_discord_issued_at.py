# FOR UPDATE: the pinned rows stay locked from the check to the write (one transaction).
_SELECT = sa.text(
    "SELECT plan_id, doc->>'issued_at' AS issued_at, doc->>'issued_at_source' AS source "
    "FROM plans WHERE plan_id = ANY(:ids) FOR UPDATE")
_STAMP = sa.text(
    "UPDATE plans SET doc = doc || jsonb_build_object("
    "'issued_at', CAST(:issued_at AS text), 'issued_at_source', 'discord') WHERE plan_id = :plan_id")
_UNSTAMP = sa.text(
    "UPDATE plans SET doc = doc - 'issued_at' - 'issued_at_source' WHERE plan_id = :plan_id")


def _check_present(docs: dict[str, dict], pins: dict[str, str]) -> None:
    missing = sorted(set(pins) - set(docs))
    if missing:
        raise RuntimeError(f"v200_001: pinned plans missing: {missing}")


def stamp(docs: dict[str, dict], pins: dict[str, str]) -> dict[str, dict]:
    """The fields to write per pinned plan; refuses a partial book or an existing issued_at."""
    _check_present(docs, pins)
    already = sorted(pid for pid in pins if docs[pid].get("issued_at"))
    if already:
        raise RuntimeError(f"v200_001: pinned plans already carry issued_at: {already}")
    return {pid: {"issued_at": pins[pid], "issued_at_source": "discord"} for pid in pins}


def unstamp(docs: dict[str, dict], pins: dict[str, str]) -> list[str]:
    """The ids to clear; refuses a partial book or a plan that is not the pinned stamp."""
    _check_present(docs, pins)
    wrong = sorted(pid for pid in pins
                   if (docs[pid].get("issued_at"), docs[pid].get("issued_at_source"))
                   != (pins[pid], "discord"))
    if wrong:
        raise RuntimeError(f"v200_001: not the pinned discord stamp: {wrong}")
    return sorted(pins)


def _selected(conn, pins: dict[str, str]) -> dict[str, dict]:
    rows = conn.execute(_SELECT, {"ids": list(pins)}).fetchall()
    return {pid: {"issued_at": at, "issued_at_source": source} for pid, at, source in rows}


def apply_upgrade(conn, pins: dict[str, str] = PINNED_ISSUED_AT) -> int:
    docs = _selected(conn, pins)
    if not docs:
        log.info("v200_001: none of the %d pinned plans exist here (not the production book); "
                 "nothing to %s", len(pins), "stamp")
        return 0
    fields = stamp(docs, pins)
    for pid, values in fields.items():
        conn.execute(_STAMP, {"issued_at": values["issued_at"], "plan_id": pid})
    log.info("v200_001: stamped %d plans with their Discord issue time", len(fields))
    return len(fields)


def apply_downgrade(conn, pins: dict[str, str] = PINNED_ISSUED_AT) -> int:
    docs = _selected(conn, pins)
    if not docs:
        log.info("v200_001: none of the %d pinned plans exist here (not the production book); "
                 "nothing to %s", len(pins), "unstamp")
        return 0
    ids = unstamp(docs, pins)
    for pid in ids:
        conn.execute(_UNSTAMP, {"plan_id": pid})
    log.info("v200_001: removed the Discord issue time from %d plans", len(ids))
    return len(ids)


def upgrade() -> None:
    apply_upgrade(op.get_bind())


def downgrade() -> None:
    apply_downgrade(op.get_bind())
